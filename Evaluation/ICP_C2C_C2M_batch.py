def get_id(name):
    """Extract the coded participant identifier from a filename.

    The identifier is defined as the portion of the filename preceding the
    first underscore or hyphen.

    Args:
        name: Input filename.

    Returns:
        The extracted participant identifier.
    """
    return re.split(r"[_-]", os.path.splitext(name)[0])[0]


def add_header(path):
    """Add the corresponding column header to an exported ASC file.

    Existing CloudCompare comment lines and blank lines are omitted so that
    the output contains a single standardized header followed by numerical
    data.

    Args:
        path: Path to the ASC file to be modified.
    """
    with open(path, "r") as f:
        lines = f.readlines()

    with open(path, "w") as f:
        f.write(HEADER)
        for line in lines:
            if line.startswith("//") or not line.strip():
                continue
            f.write(line)


def compute_metrics(ref_mesh, comp_mesh, out_file):
    """Compute C2C and signed C2M distances relative to an SPG reference.

    Cloud-to-cloud distances are calculated between the comparison point
    cloud and the point cloud associated with the reference mesh. Signed
    cloud-to-mesh distances are then calculated against the continuous
    reference mesh. The resulting comparison cloud is exported as an ASC
    file with the appropriate column header.

    Args:
        ref_mesh: SPG reference mesh.
        comp_mesh: Comparison mesh.
        out_file: Destination path for the exported ASC file.

    Raises:
        RuntimeError: If the point cloud cannot be saved successfully.
    """
    ref_cloud = ref_mesh.getAssociatedCloud()
    comp_cloud = comp_mesh.getAssociatedCloud()

    p1 = cc.Cloud2CloudDistancesComputationParams()
    p1.octreeLevel = cc.DistanceComputationTools.determineBestOctreeLevel(
        comp_cloud,
        refCloud=ref_cloud
    )
    cc.DistanceComputationTools.computeCloud2CloudDistances(
        comp_cloud,
        ref_cloud,
        p1
    )

    p2 = cc.Cloud2MeshDistancesComputationParams()
    p2.signedDistances = True
    p2.octreeLevel = cc.DistanceComputationTools.determineBestOctreeLevel(
        comp_cloud,
        refMesh=ref_mesh
    )
    cc.DistanceComputationTools.computeCloud2MeshDistances(
        comp_cloud,
        ref_mesh,
        p2
    )

    ret = cc.SavePointCloud(comp_cloud, out_file)
    if ret != cc.CC_FILE_ERROR.CC_FERR_NO_ERROR:
        raise RuntimeError("Error saving ASC file")

    add_header(out_file)


def build(folder):
    """Create a participant-ID-to-filepath mapping for PLY models.

    Args:
        folder: Directory containing the PLY files.

    Returns:
        A dictionary mapping each participant identifier to its PLY filepath.
    """
    return {
        get_id(f): os.path.join(folder, f)
        for f in os.listdir(folder)
        if f.lower().endswith(".ply")
    }


