    comp = build(COMP_DIR)

    # Restrict the analysis to participant IDs available in both modalities.
    ids = sorted(set(spg) & set(comp))
    print("Common participants:", len(ids))

    ok = err = 0

    for pid in ids:

        # Exclude predefined cases and ST/P relatives from the final analysis.
        if pid in EXCLUDED_IDS or pid.startswith(("BRSTP", "COSTP")):
            print(f"\nSkipping {pid}")
            continue

        try:
            print("\nProcessing", pid)

            ref_mesh = cc.loadMesh(spg[pid])
            comp_mesh = cc.loadMesh(comp[pid])

            if ref_mesh is None or comp_mesh is None:
                raise RuntimeError("Error loading mesh.")

            # Compute distance fields without ICP when explicitly enabled.
            if GENERATE_NOICP:
                compute_metrics(
                    ref_mesh,
                    comp_mesh,
                    os.path.join(NOICP_DIR, f"{pid}_C2C_C2M.asc")
                )

            # Apply ICP before computing the final distance fields.
            if GENERATE_ICP:

                ref_mesh = cc.loadMesh(spg[pid])
                comp_mesh = cc.loadMesh(comp[pid])

                if ref_mesh is None or comp_mesh is None:
                    raise RuntimeError("Error loading mesh.")

                res = cc.ICP(
                    comp_mesh,
                    ref_mesh,
                    removeFarthestPoints=True
                )
                print("ICP RMS:", res.finalRMS)

                comp_mesh.applyRigidTransformation(res.transMat)

                original = os.path.splitext(os.path.basename(comp[pid]))[0]
                ply_out = os.path.join(
                    COMP_ICP_DIR,
                    original + "_ICP.ply"
                )

                ret = cc.SaveMesh(comp_mesh, ply_out)
                if ret != cc.CC_FILE_ERROR.CC_FERR_NO_ERROR:
                    raise RuntimeError("Error saving PLY file")

                compute_metrics(
                    ref_mesh,
                    comp_mesh,
                    os.path.join(
                        ICP_DIR,
                        f"{pid}_ICP_C2C_C2M.asc"
                    )
                )

            ok += 1

        except Exception as e:
            err += 1
            print("Error", pid, e)

    print("\nSuccessful:", ok)
    print("Failed:", err)