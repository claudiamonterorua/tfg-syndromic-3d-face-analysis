function id = extract_id(filename)
    %EXTRACT_ID Extract the coded participant identifier from a filename.
    %
    %   id = EXTRACT_ID(filename) removes the file extension and returns
    %   the leading identifier before the first underscore or hyphen.

    [~, base_name, ~] = fileparts(filename);

    id = regexp( ...
        base_name, ...
        "^[^_-]+", ...
        "match", ...
        "once" ...
    );

end


function method_dir = find_existing_method_dir( ...
    data_dir, ...
    relative_paths ...
)
    %FIND_EXISTING_METHOD_DIR Return the first existing method directory.
    %
    %   method_dir = FIND_EXISTING_METHOD_DIR(data_dir, relative_paths)
    %   evaluates the candidate relative paths in order and returns the
    %   first directory found. An empty string is returned when none exist.

    method_dir = "";

    for k = 1:length(relative_paths)

        candidate = fullfile( ...
            data_dir, ...
            relative_paths{k} ...
        );

        if exist(candidate, "dir")
            method_dir = string(candidate);
            return;
        end

    end

end


function [pc_x, pc_y, pc_z] = scaling(x, y, z)
    %SCALING Scale landmark configurations by centroid size.
    %
    %   [pc_x, pc_y, pc_z] = SCALING(x, y, z) centres each landmark
    %   configuration and divides its coordinates by centroid size.
    %   The numerical formulation is identical to the original PPD.m
    %   implementation.

    num_point = size(x, 2);

    C = [ ...
        mean(x, 2), ...
        mean(y, 2), ...
        mean(z, 2) ...
    ];

    CS = sum( ...
        ( ...
            (x - repmat(C(:, 1), 1, num_point)).^2 + ...
            (y - repmat(C(:, 2), 1, num_point)).^2 + ...
            (z - repmat(C(:, 3), 1, num_point)).^2 ...
        ), ...
        2 ...
    ).^0.5;

    pc_x = ( ...
        x - repmat(C(:, 1), 1, num_point) ...
    ) ./ repmat(CS, 1, num_point);

    pc_y = ( ...
        y - repmat(C(:, 2), 1, num_point) ...
    ) ./ repmat(CS, 1, num_point);

    pc_z = ( ...
        z - repmat(C(:, 3), 1, num_point) ...
    ) ./ repmat(CS, 1, num_point);

end


function [pc_x_r, pc_y_r, pc_z_r] = rotation( ...
    pc_x, ...
    pc_y, ...
    pc_z ...
)
    %ROTATION Generate candidate landmark rotations.
    %
    %   [pc_x_r, pc_y_r, pc_z_r] = ROTATION(pc_x, pc_y, pc_z)
    %   evaluates rotations from -5 to +5 degrees in one-degree
    %   increments around the three coordinate axes. This reproduces
    %   the angular search used in the original PPD.m implementation.

    num_points = size(pc_x, 2);
    num_samples = size(pc_x, 1);

    a = (-5:1:5) * (pi / 180);

    pc_x_r = zeros( ...
        num_samples, ...
        num_points, ...
        length(a), ...
        length(a), ...
        length(a) ...
    );

    pc_y_r = zeros( ...
        num_samples, ...
        num_points, ...
        length(a), ...
        length(a), ...
        length(a) ...
    );

    pc_z_r = zeros( ...
        num_samples, ...
        num_points, ...
        length(a), ...
        length(a), ...
        length(a) ...
    );

    for a1 = 1:length(a)

        R1 = [ ...
            cos(a(a1)), -sin(a(a1)), 0; ...
            sin(a(a1)),  cos(a(a1)), 0; ...
            0,           0,          1 ...
        ];

        for a2 = 1:length(a)

            R2 = [ ...
                cos(a(a2)), 0, sin(a(a2)); ...
                0,          1, 0; ...
               -sin(a(a2)), 0, cos(a(a2)) ...
            ];

            for a3 = 1:length(a)

                R3 = [ ...
                    1, 0,          0; ...
                    0, cos(a(a3)), -sin(a(a3)); ...
                    0, sin(a(a3)),  cos(a(a3)) ...
                ];

                for p = 1:num_samples

                    pcr = R1 * R2 * R3 * [ ...
                        pc_x(p, :); ...
                        pc_y(p, :); ...
                        pc_z(p, :) ...
                    ];

                    pc_x_r(p, :, a1, a2, a3) = pcr(1, :);
                    pc_y_r(p, :, a1, a2, a3) = pcr(2, :);
                    pc_z_r(p, :, a1, a2, a3) = pcr(3, :);

                end
            end
        end
    end
end


function [PC_T, procrustes_coord] = procrustes_custom( ...
    pc_x, ...
    pc_y, ...
    pc_z, ...
    pc_x_r, ...
    pc_y_r, ...
    pc_z_r ...
)
    %PROCRUSTES_CUSTOM Perform the custom Procrustes alignment procedure.
    %
    %   [PC_T, procrustes_coord] = PROCRUSTES_CUSTOM(...) iteratively
    %   selects the candidate rotation that minimises the discrepancy
    %   from the current mean landmark configuration.
    %
    %   The numerical procedure reproduces the original PPD.m method.
    %   The function name is intentionally distinct from MATLAB's
    %   built-in procrustes function.

    num_points = size(pc_x, 2);
    num_samples = size(pc_x, 1);
    num_angles = size(pc_x_r, 3);

    mean_shape = [ ...
        pc_x(1, :)', ...
        pc_y(1, :)', ...
        pc_z(1, :)' ...
    ];

    mean_shape_pc = mean_shape;

    for j = 1:10

        dist = squeeze( ...
            sum( ...
                ( ...
                    ( ...
                        repmat( ...
                            mean_shape_pc(:, 1)', ...
                            num_samples, ...
                            1, ...
                            num_angles, ...
                            num_angles, ...
                            num_angles ...
                        ) ...
                        - pc_x_r ...
                    ).^2 ...
                    + ...
                    ( ...
                        repmat( ...
                            mean_shape_pc(:, 2)', ...
                            num_samples, ...
                            1, ...
                            num_angles, ...
                            num_angles, ...
                            num_angles ...
                        ) ...
                        - pc_y_r ...
                    ).^2 ...
                    + ...
                    ( ...
                        repmat( ...
                            mean_shape_pc(:, 3)', ...
                            num_samples, ...
                            1, ...
                            num_angles, ...
                            num_angles, ...
                            num_angles ...
                        ) ...
                        - pc_z_r ...
                    ).^2 ...
                ).^0.5, ...
                2 ...
            ) ...
            ./ num_points ...
        );

        [M, id_a1] = min(dist, [], 2);
        id_a1 = squeeze(id_a1);

        M = squeeze(M);

        [M, id_a2] = min(M, [], 2);
        M = squeeze(M);
        id_a2 = squeeze(id_a2);

        [~, id_a3] = min(M, [], 2);

        for i = 1:num_samples

            pc_x(i, :) = pc_x_r( ...
                i, ...
                :, ...
                id_a1(i, id_a2(i, id_a3(i)), id_a3(i)), ...
                id_a2(i, id_a3(i)), ...
                id_a3(i) ...
            );

            pc_y(i, :) = pc_y_r( ...
                i, ...
                :, ...
                id_a1(i, id_a2(i, id_a3(i)), id_a3(i)), ...
                id_a2(i, id_a3(i)), ...
                id_a3(i) ...
            );

            pc_z(i, :) = pc_z_r( ...
                i, ...
                :, ...
                id_a1(i, id_a2(i, id_a3(i)), id_a3(i)), ...
                id_a2(i, id_a3(i)), ...
                id_a3(i) ...
            );

        end

        mean_shape = [ ...
            mean(pc_x)', ...
            mean(pc_y)', ...
            mean(pc_z)' ...
        ];

        mean_shape_C = mean(mean_shape);

        mean_shape_CS = sqrt(sum( ...
            (mean_shape(:, 1) - mean_shape_C(1)).^2 + ...
            (mean_shape(:, 2) - mean_shape_C(2)).^2 + ...
            (mean_shape(:, 3) - mean_shape_C(3)).^2 ...
        ));

        mean_shape_pc = ( ...
            mean_shape ...
            - repmat( ...
                mean_shape_C, ...
                num_points, ...
                1 ...
            ) ...
        ) ./ mean_shape_CS;

    end

    x_m = [ ...
        mean_shape(:, 1); ...
        mean_shape(:, 2); ...
        mean_shape(:, 3) ...
    ];

    procrustes_coord = [ ...
        pc_x, ...
