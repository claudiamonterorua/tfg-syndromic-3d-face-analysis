% ============================================================
% AUTOMATIC CS AND PPD EVALUATION
%
% This script combines the original CS.m and PPD.m procedures.
% All available methods and countries are processed automatically
% and compared against SPG as the reference modality.
%
% Output:
%   Method | Country | CS | PPD
%
% CS  = correlation of Centroid Size values with SPG
% PPD = correlation of Procrustes Point Distances with SPG
% ============================================================


% ============================================================
% CONFIGURATION
% ============================================================

FONT_TICKS = 24;
FONT_LABELS = 36;
FONT_TITLE = 38;

ROOT_DIR = ...
    "C:\path\to\project";

DATA_DIR = fullfile(ROOT_DIR, "02_Dades");

OUT_DIR = fullfile( ...
    ROOT_DIR, ...
    "03_Dades_Analitzades", ...
    "CS_PPD_results" ...
);

OUTPUT_FILE = fullfile(OUT_DIR, "CS_PPD.xlsx");

FIG_DIR = fullfile(OUT_DIR, "Figures");

if ~exist(OUT_DIR, "dir")
    mkdir(OUT_DIR);
end

if ~exist(FIG_DIR, "dir")
    mkdir(FIG_DIR);
end


% ============================================================
% METHODS
%
% For HRN configurations, the script automatically searches for:
%   21_landmarks_ICP
%
% The first existing directory associated with each method is used.
% ============================================================

methods = struct( ...
    "Name", { ...
        "MP", ...
        "HRN1 Mid", ...
        "HRN3 Mid", ...
        "HRN5 Mid", ...
        "HRN5 High", ...
        "HRN10 Mid", ...
        "HRN10 High" ...
    }, ...
    "RelativePaths", { ...
        {fullfile("MP", "21_landmarks_ICP")}, ...
        { ...
            fullfile("HRN", "HRN1", "Mid", "21_landmarks_ICP")}, ...
        { ...
            fullfile("HRN", "HRN3", "Mid", "21_landmarks_ICP")}, ...
        { ...
            fullfile("HRN", "HRN5", "Mid", "21_landmarks_ICP")}, ...
        { ...
            fullfile("HRN", "HRN5", "High", "21_landmarks_ICP")}, ...
        { ...
            fullfile("HRN", "HRN10", "Mid", "21_landmarks_ICP")}, ...
        { ...
            fullfile("HRN", "HRN10", "High", "21_landmarks_ICP")} ...
    } ...
);

countries = ["BR", "CO"];

numLandmarks = 21;

EXCLUDED_IDS = [
    "BRSTM0556"
    "BRCTC0542"
    "BRSTM0278"
    "BRSTM0294"
    "BRSTP0090"
    "BRSTP0370"
];


% ============================================================
% RESULT STORAGE
% ============================================================

result_method = strings(0, 1);
result_country = strings(0, 1);
result_cs = zeros(0, 1);
result_ppd = zeros(0, 1);


% ============================================================
% PROCESS ALL METHODS AND COUNTRIES
% ============================================================

for c = 1:length(countries)

    country = countries(c);

    spg_dir = fullfile( ...
        DATA_DIR, ...
        "SPG", ...
        "21_landmarks", ...
        country, ...
        "Todos" ...
    );

    if ~exist(spg_dir, "dir")
        warning("SPG directory does not exist for %s: %s", country, spg_dir);
        continue;
    end

    spg_files = dir(fullfile(spg_dir, "**", "*.txt"));

    % Build an ID-to-SPG-file index once for the current country.
    spg_map = containers.Map();

    for j = 1:length(spg_files)

        spg_id = extract_id(spg_files(j).name);

        if ~isKey(spg_map, spg_id)
            spg_map(spg_id) = fullfile( ...
                spg_files(j).folder, ...
                spg_files(j).name ...
            );
        end

    end


    for m = 1:length(methods)

        method_name = methods(m).Name;

        method_base_dir = find_existing_method_dir( ...
            DATA_DIR, ...
            methods(m).RelativePaths ...
        );

        if method_base_dir == ""
            warning( ...
                "No directory was found for %s", ...
                method_name ...
            );

            result_method(end + 1, 1) = method_name;
            result_country(end + 1, 1) = country;
            result_cs(end + 1, 1) = NaN;
            result_ppd(end + 1, 1) = NaN;

            continue;
        end

        % ============================================================
        % VALID ANALYTICAL GROUPS ONLY
        %
        %   CT    -> controls
        %   ST/M  -> Turner syndrome
        %
        % ST/P participants and the "Todos" directory are excluded
        % from the analytical comparison.
        % ============================================================

        ct_dir = fullfile( ...
            method_base_dir, ...
            country, ...
            "CT" ...
        );

        st_m_dir = fullfile( ...
            method_base_dir, ...
            country, ...
            "ST", ...
            "M" ...
        );

        ct_files = dir( ...
            fullfile(ct_dir, "*.txt") ...
        );

        st_m_files = dir( ...
            fullfile(st_m_dir, "*.txt") ...
        );

        method_files = [ ...
            ct_files; ...
            st_m_files ...
        ];

        fprintf("\nCT: %d files\n", length(ct_files));
        fprintf("ST/M: %d files\n", length(st_m_files));
        fprintf("Total valid files: %d\n", length(method_files));

        % ------------------------------------------------------------
        % LOAD METHOD-SPG PAIRS ONCE
        %
        % The same paired landmark configurations are reused for both
        % CS and PPD calculations to ensure consistent comparisons.
        % ------------------------------------------------------------

        landmarks_method_all = {};
        landmarks_spg_all = {};
        matched_ids = strings(0, 1);

        for i = 1:length(method_files)

            method_file = fullfile( ...
                method_files(i).folder, ...
                method_files(i).name ...
            );

            id_method = extract_id(method_files(i).name);

            if any(string(id_method) == EXCLUDED_IDS)
                fprintf("Excluded: %s\n", id_method);
                continue;
            end

            if ~isKey(spg_map, id_method)
                fprintf("Not found in SPG: %s\n", id_method);
                continue;
            end

            spg_file = spg_map(id_method);

            data1 = load(method_file);
            data2 = load(spg_file);

            if size(data1, 1) ~= numLandmarks || size(data1, 2) < 3
                warning( ...
                    "%s does not contain at least %d XYZ landmarks.", ...
                    method_file, ...
                    numLandmarks ...
                );
                continue;
            end

            if size(data2, 1) ~= numLandmarks || size(data2, 2) < 3
                warning( ...
                    "%s does not contain at least %d XYZ landmarks.", ...
                    spg_file, ...
                    numLandmarks ...
                );
                continue;
            end

            % As in the original implementations, only XYZ coordinates
            % are retained for subsequent morphometric calculations.
            landmarks1 = data1(:, 1:3);
            landmarks2 = data2(:, 1:3);

            landmarks_method_all{end + 1, 1} = landmarks1;
            landmarks_spg_all{end + 1, 1} = landmarks2;
            matched_ids(end + 1, 1) = id_method;

        end

        n_pairs = length(landmarks_method_all);

        fprintf("Valid method-SPG pairs: %d\n", n_pairs);

        if n_pairs < 2
            warning( ...
                "Insufficient paired cases to calculate correlations: %s - %s", ...
                method_name, ...
                country ...
            );

            result_method(end + 1, 1) = method_name;
            result_country(end + 1, 1) = country;
            result_cs(end + 1, 1) = NaN;
            result_ppd(end + 1, 1) = NaN;

            continue;
        end


        % ============================================================
        % 1. CENTROID SIZE
        %
        % The calculation follows the original CS.m implementation:
        % Centroid Size is obtained from the summed squared distances
        % of all landmarks from their configuration centroid.
        % ============================================================

        centroid_size_all = zeros(n_pairs, 2);

        for i = 1:n_pairs

            landmarks1 = landmarks_method_all{i};
            landmarks2 = landmarks_spg_all{i};

            centroid1 = [ ...
                mean(landmarks1(:, 1)), ...
                mean(landmarks1(:, 2)), ...
                mean(landmarks1(:, 3)) ...
            ];

            centroid_size1 = sqrt(sum( ...
                (landmarks1(:, 1) - centroid1(1)).^2 + ...
                (landmarks1(:, 2) - centroid1(2)).^2 + ...
                (landmarks1(:, 3) - centroid1(3)).^2 ...
            ));

            centroid2 = [ ...
                mean(landmarks2(:, 1)), ...
                mean(landmarks2(:, 2)), ...
                mean(landmarks2(:, 3)) ...
            ];

            centroid_size2 = sqrt(sum( ...
                (landmarks2(:, 1) - centroid2(1)).^2 + ...
                (landmarks2(:, 2) - centroid2(2)).^2 + ...
                (landmarks2(:, 3) - centroid2(3)).^2 ...
            ));

            centroid_size_all(i, 1) = centroid_size1;
            centroid_size_all(i, 2) = centroid_size2;

        end

        x_cs = centroid_size_all(:, 1);
        y_cs = centroid_size_all(:, 2);

        R_CS = corrcoef(x_cs, y_cs);
        coef_corr_CS = R_CS(1, 2);

        % Compute the regression line following the original procedure.
        p_cs = polyfit(x_cs, y_cs, 1);
        y_fit_cs = polyval(p_cs, x_cs);


        % ============================================================
        % 2. PROCRUSTES POINT DISTANCES
        %
        % The procedure follows the original PPD.m workflow:
        % scaling -> rotation -> Procrustes alignment ->
        % pairwise distances -> correlation.
        % ============================================================

        X1 = zeros(n_pairs, numLandmarks);
        Y1 = zeros(n_pairs, numLandmarks);
        Z1 = zeros(n_pairs, numLandmarks);

        X2 = zeros(n_pairs, numLandmarks);
        Y2 = zeros(n_pairs, numLandmarks);
        Z2 = zeros(n_pairs, numLandmarks);

        for i = 1:n_pairs

            landmarks1 = landmarks_method_all{i};
            landmarks2 = landmarks_spg_all{i};

            X1(i, :) = landmarks1(:, 1)';
            Y1(i, :) = landmarks1(:, 2)';
            Z1(i, :) = landmarks1(:, 3)';

            X2(i, :) = landmarks2(:, 1)';
            Y2(i, :) = landmarks2(:, 2)';
            Z2(i, :) = landmarks2(:, 3)';

        end

        [pc1_x, pc1_y, pc1_z] = scaling(X1, Y1, Z1);
        [pc2_x, pc2_y, pc2_z] = scaling(X2, Y2, Z2);

        [pc1_x_r, pc1_y_r, pc1_z_r] = rotation( ...
            pc1_x, pc1_y, pc1_z ...
        );

        [pc2_x_r, pc2_y_r, pc2_z_r] = rotation( ...
            pc2_x, pc2_y, pc2_z ...
        );

        [~, procrustes_coord1] = procrustes_custom( ...
            pc1_x, ...
            pc1_y, ...
            pc1_z, ...
            pc1_x_r, ...
            pc1_y_r, ...
            pc1_z_r ...
        );

        [~, procrustes_coord2] = procrustes_custom( ...
            pc2_x, ...
            pc2_y, ...
            pc2_z, ...
            pc2_x_r, ...
            pc2_y_r, ...
            pc2_z_r ...
        );

        distances1 = pdist( ...
            procrustes_coord1, ...
            "euclidean" ...
        );

        distances2 = pdist( ...
            procrustes_coord2, ...
            "euclidean" ...
        );

        x_ppd = distances1';
        y_ppd = distances2';

        R_PPD = corrcoef(x_ppd, y_ppd);
        coef_corr_PPD = R_PPD(1, 2);

        % Compute the regression line following the original procedure.
        p_ppd = polyfit(x_ppd, y_ppd, 1);
        y_fit_ppd = polyval(p_ppd, x_ppd);


        % ============================================================
        % STORE RESULTS
        % ============================================================

        result_method(end + 1, 1) = method_name;
        result_country(end + 1, 1) = country;
        result_cs(end + 1, 1) = coef_corr_CS;
        result_ppd(end + 1, 1) = coef_corr_PPD;

        fprintf("CS  = %.6f\n", coef_corr_CS);
        fprintf("PPD = %.6f\n", coef_corr_PPD);


        % ============================================================
        % CS FIGURE
        % ============================================================

        fig_cs = figure('Visible', 'off', 'Position', [100 100 1100 700]);

        scatter(x_cs, y_cs, "filled");
        hold on;
        plot(x_cs, y_fit_cs, "-r", "LineWidth", 2);
        hold off;

        title(sprintf("CS correlation: %.4f", coef_corr_CS), ...
            "FontSize", FONT_TITLE);

        xlabel(method_name + " - " + country + " centroid size", ...
            "FontSize", FONT_LABELS);

        ylabel("SPG centroid size", ...
            "FontSize", FONT_LABELS);

        set(gca, "FontSize", FONT_TICKS);
        grid on;

        safe_method_name = regexprep(method_name, "\s+", "_");
        safe_method_name = strrep(strrep(safe_method_name, "Mid", "mid"), "High", "high");

        exportgraphics( ...
            fig_cs, ...
            fullfile( ...
                FIG_DIR, ...
                safe_method_name + "_" + country + "_CS.png" ...
            ), ...
            'Resolution', ...
            300 ...
        );

        close(fig_cs);


        % ============================================================
        % PPD FIGURE
        % ============================================================

        fig_ppd = figure('Visible', 'off', 'Position', [100 100 1100 700]);

        scatter(x_ppd, y_ppd, "filled");
        hold on;
        plot(x_ppd, y_fit_ppd, "-r", "LineWidth", 2);
        hold off;

        title(sprintf("PPD correlation: %.4f", coef_corr_PPD), ...
            "FontSize", FONT_TITLE);

        xlabel(method_name + " - " + country + " procrustes point distances", ...
            "FontSize", FONT_LABELS);

        ylabel("SPG procrustes point distances", ...
            "FontSize", FONT_LABELS);

        set(gca, "FontSize", FONT_TICKS);
        grid on;

        exportgraphics( ...
            fig_ppd, ...
            fullfile( ...
                FIG_DIR, ...
                safe_method_name + "_" + country + "_PPD.png" ...
            ), ...
            'Resolution', ...
            300 ...
        );

        close(fig_ppd);

    end
end


